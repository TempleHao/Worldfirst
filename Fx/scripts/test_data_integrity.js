"use strict";
/* This test reads the exact current FX snapshot, not illustrative prices. */
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const vm=require("node:vm");
const dir=path.resolve(__dirname,"..");
const js=fs.readFileSync(path.join(dir,"app.js"),"utf8");
const start=js.indexOf("const RSS_DOMAINS=");
const end=js.indexOf("function rateFor(",start);
assert(start>0&&end>start,"source integrity helpers missing");
const ctx={URL,Date,Number,Set,Map,Math,Array,String,Boolean,Error};
vm.createContext(ctx);
vm.runInContext('const R14=["USD/CNH","USD/CNY","USD/HKD","EUR/USD","USD/JPY","GBP/USD","AUD/USD","NZD/USD","USD/CAD","USD/CHF","USD/SGD","EUR/GBP","EUR/JPY","EUR/CHF"]; function ms(x){const n=Date.parse(x);return Number.isFinite(n)?n:NaN;}',ctx);
vm.runInContext(js.slice(start,end),ctx);
const {instruments}=JSON.parse(fs.readFileSync(path.join(dir,"data/market.json"),"utf8"));
const {articles}=JSON.parse(fs.readFileSync(path.join(dir,"data/articles.json"),"utf8"));
assert(instruments.length>=13,"missing 13 official daily reference pairs");
for(const m of instruments)assert(ctx.validOfficialRate(m),m.pair+" should pass authentic source integrity");
for(const a of articles)assert(ctx.validRSSArticle(a),"RSS item must have known original source and date: "+a.id);
const correct=instruments.find(x=>x.pair==="USD/CNY");
assert(correct,"missing onshore example");
const malformed=(patch)=>({...correct,...patch});
assert(!ctx.validOfficialRate(malformed({value:correct.value+0.02})),"corrupted quote vs historical last observation");
assert(!ctx.validOfficialRate(malformed({source:"Unknown AI provider"})),"untrusted source");
assert(!ctx.validOfficialRate(malformed({source_url:"https://another.example.com/quote"})),"untrusted domain");
assert(!ctx.validOfficialRate(malformed({date:"2026-11-31"})),"invalid calendar date");
assert(!ctx.validOfficialRate(malformed({pair:"USD/CNH"})),"never repurpose CNY as CNH");
assert(!ctx.validOfficialRate(malformed({change_5_published_days_pct:88.88})),"mismatched 5-day change");
const a=articles[0];
assert(!ctx.validRSSArticle({...a,source:"Unknown provider"}));
assert(!ctx.validRSSArticle({...a,source_url:"https://example.com/rss"}));
assert(!ctx.validRSSArticle({...a,published_at:"not-a-date"}));
assert(!ctx.validRSSArticle({...a,url:"javascript:alert(1)"}));
const boj=articles.find(x=>x.source==="日本央行·官方发布"&&x.url.startsWith("http://"));
if(boj)assert(ctx.validRSSArticle(boj),"real BOJ official legacy URL must remain visible");
assert(!ctx.validRSSArticle({...a,url:"http://cn.investing.com/news/example"}),"ordinary RSS item must not silently downgrade HTTPS");

console.log("Data integrity tests passed: "+instruments.length+" authentic source-checked rates, "+articles.length+" RSS metadata items; malformed records fail closed.");
